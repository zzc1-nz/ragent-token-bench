def tbl(headers, rows):
    """Markdown 表格。"""
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def ul(items):
    return "\n".join("- " + str(i) for i in items)


def ol(items):
    return "\n".join("%d. %s" % (i + 1, s) for i, s in enumerate(items))


def pick(rs, *opts):
    return opts[rs.randrange(len(opts))]


def qa(q, a, followups=None):
    """一个 QA 种子：问题、参考答案、指代式追问列表 [(q, a), ...]。"""
    return {"q": q, "a": a, "fu": list(followups or [])}


def fit_answer(text, filler):
    """把参考答案长度收敛到 80~200 字符，清理标点，并保证尾部不堆叠套话。

    补齐策略：最多追加 2 句收尾语，且优先选能一次补足长度的长句，
    避免出现「具体条款以文档正文为准。完整流程见正文……具体标准以现行制度为准……」这类三段套话。
    """
    text = text.strip().replace("%%", "%").replace("。。", "。")

    # 已有的收尾套话若重复出现，去重
    for dup in ("具体条款以文档正文为准。", "具体条款与时效以对应文档正文为准。"):
        while text.count(dup) > 1:
            text = text.replace(dup, "", 1)

    # 补齐到下限：按「短 → 长」顺序最多追加 2 句
    if len(text) < 80:
        candidates = [
            filler,
            "具体条款、办理流程与所需材料以对应文档正文为准，如有疑问可联系归口部门书面确认。",
            "相关标准每年复审一次，调整后以最新公告为准。",
        ]
        added = 0
        for c in candidates:
            if len(text) >= 80 or added >= 2:
                break
            if not c or c in text:
                continue
            text = text.rstrip("。") + "。" + c
            added += 1

    # 极少数仍不足的，一次性补到 80（不再追加第二句）
    if len(text) < 80:
        text = (text.rstrip("。") + "。具体标准与时效以现行制度及对应文档正文为准。")
    if len(text) < 80:
        text = (text + "详情见文档正文。")[:200]

    # 过长：按句号截断，保证不出现半句
    if len(text) > 200:
        cut = text.rfind("。", 0, 200)
        if cut < 80:
            cut = text.rfind("；", 0, 200)
        if cut < 80:
            cut = 199
        text = text[:cut + 1]

    return text.replace("。。", "。")


