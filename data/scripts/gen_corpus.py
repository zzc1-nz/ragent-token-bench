def normalize_md(text):
    """规范化 Markdown：保证标题、列表、段落之间有空行，避免段落粘连。"""
    # 1) 句中出现的二级标题：前面补空行
    text = re.sub(r'(?<=[。；：）\)])[ \t]*(## )', r'\n\n\1', text)
    # 2) 句中出现的有序列表起始：前面补空行
    text = re.sub(r'(?<=[。；：）\)])[ \t]*(\d+\. )(?=\S)', r'\n\n\1', text)
    # 3) 句中出现的无序列表起始：前面补空行
    text = re.sub(r'(?<=[。；：）\)])[ \t]*(- )(?=\S)', r'\n\n\1', text)
    # 4) 句末紧跟的引导语（如「注意事项：」）：前面补空行
    text = re.sub(r'。([\u4e00-\u9fa5A-Za-z0-9、（）]{1,12}：)(?=\n)', r'。\n\n\1', text)
    # 5) 压缩多余空行
    text = re.sub(r'\n{3,}', '\n\n', text)
    # 6) 清理百分号转义残留（模板里部分字符串未走 % 格式化）
    text = text.replace("%%", "%")
    return text.strip()


def build_doc(rs, domain, idx, seq):
    """生成一篇文档：返回 (doc dict, [(QA 种子, 章节名), ...])。

    seq 为全局序号（1..200），用于写入唯一的文档编号，保证正文互不相同。
    """
    global DOC_HAS_TABLE
    gens, themes, titles, facts_fn = DOMAIN_SPEC[domain]
    theme_keys = list(themes.keys())
    tkey = theme_keys[idx % len(theme_keys)]
    DOC_HAS_TABLE = (idx % 3 == 0)

    facts = facts_fn(rs) if facts_fn else None
    if domain == "vacuum":
        focus = focus_v(rs, idx)
        focus["want_table"] = DOC_HAS_TABLE
    else:
        focus = facts

    title = titles[tkey](rs, focus)

    parts = ["# " + title, "", pick(rs, *DOMAIN_INTRO[domain]), ""]
    seeds = []
    used_sections = []
    cand = list(themes[tkey])
    body_len = len("\n".join(parts))

    i = 0
    while i < len(cand):
        gname = cand[i]
        sec = gens[gname](rs, facts, focus)
        parts.append(sec["h"])
        parts.append("")
        parts.append(sec["b"])
        parts.append("")
        body_len += len(sec["h"]) + len(sec["b"]) + 2
        used_sections.append(gname)
        for s in sec["q"]:
            seeds.append((s, gname))
        i += 1
        if i >= 3 and body_len >= 1150:
            break

    ch, cb = CLOSING[domain]
    parts.extend([ch, "", cb, ""])
    body_len += len(ch) + len(cb) + 2

    # 文档元信息：每篇唯一编号/版本/生效日期，同时确保正文互不相同
    meta = (
        "## 文档信息\n\n"
        "- 文档编号：KB-%s-%04d\n"
        "- 文档版本：v%d.%d\n"
        "- 生效日期：%d-%02d-%02d\n"
        "- 复审周期：%d 个月\n"
        "- 归口部门：%s\n"
        "- 适用版本：%s"
    ) % ({"vacuum": "VAC", "finance": "FIN", "hr": "HR", "tech": "TEC", "policy": "POL"}[domain],
         seq,
         rs.randrange(1, 5), rs.randrange(0, 10),
         rs.choice([2024, 2025, 2026]), rs.randrange(1, 13), rs.randrange(1, 29),
         rs.choice([6, 12, 12, 24]),
         {"vacuum": "客户服务中心", "finance": "财务共享中心", "hr": "人力资源部",
          "tech": "基础架构团队", "policy": "安全与合规团队"}[domain],
         "全部在售批次" if domain == "vacuum" else "现行制度")
    parts.extend([meta, ""])

    # 长度兜底：不足 1200 继续追加章节，超过 2950 从尾部删章节
    while body_len < 1250 and i < len(cand):
        sec = gens[cand[i]](rs, facts, focus)
        parts.insert(-4, sec["b"])
        parts.insert(-4, sec["h"])
        parts.insert(-4, "")
        body_len += len(sec["h"]) + len(sec["b"]) + 2
        used_sections.append(cand[i])
        for s in sec["q"]:
            seeds.append((s, cand[i]))
        i += 1

    text = normalize_md("\n".join(parts))
    # 极端情况兜底：仍超长则截断到 2980 并补齐标点
    if len(text) > 2990:
        cut = text.rfind("\n\n", 0, 2980)
        text = normalize_md(text[:cut if cut > 1200 else 2980])
    return ({"title": title, "domain": domain, "text": text,
             "chunksHint": int(math.ceil(len(text) / 450.0))}, seeds)


def build_docs(rs):
    docs = []
    qseed = {}
    n = 0
    for domain in DOMAINS:
        for k in range(40):
            n += 1
            d, seeds = build_doc(rs, domain, k, n)
            d["docId"] = "DOC_%04d" % n
            docs.append({"docId": d["docId"], "title": d["title"], "domain": d["domain"],
                         "text": d["text"], "chunksHint": d["chunksHint"]})
            qseed[d["docId"]] = {"domain": domain, "seeds": seeds,
                                 "theme": list(DOMAIN_SPEC[domain][1].keys())[k % len(DOMAIN_SPEC[domain][1])]}
    return docs, qseed


