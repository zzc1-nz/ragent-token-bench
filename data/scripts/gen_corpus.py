DOC_HAS_TABLE = True   # 由 build_doc 按文档序号设置，tbl() 据此决定渲染表格还是列表

_RAW_TBL = tbl


def tbl(headers, rows):
    """约 1/3 文档渲染为 Markdown 表格，其余渲染为等价的无序列表（保持可读性）。"""
    if DOC_HAS_TABLE:
        return _RAW_TBL(headers, rows)
    # 列表降级时保留行首键值（如「婚假」「产假」），否则会丢失行的标识
    out = []
    for r in rows:
        rest = "；".join("%s=%s" % (h, c) for h, c in zip(headers[1:], r[1:]))
        out.append("%s：%s" % (r[0], rest))
    return ul(out)


