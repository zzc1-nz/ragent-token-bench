def write_jsonl(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只生成并打印统计，不写文件")
    args = ap.parse_args(argv)

    rs = random.Random(SEED)
    docs, qseed = build_docs(rs)

    # 标题去重：同领域内重名时追加唯一后缀，且保证正文首行同步更新
    seen = {}
    for d in docs:
        key = (d["domain"], d["title"])
        if key in seen:
            seen[key] += 1
            k = seen[key]
            base = d["title"].split("（")[0] if d["title"].count("（") > 1 else d["title"]
            # 后缀池按领域 + 序号轮转，避免重复
            suf = SUFFIX[k % len(SUFFIX)]
            cand_title = base + suf
            guard = 0
            while (d["domain"], cand_title) in seen and guard < 50:
                k += 1
                cand_title = base + SUFFIX[k % len(SUFFIX)] + "·%d" % k
                guard += 1
            seen[(d["domain"], cand_title)] = 0
            old = d["title"]
            d["title"] = cand_title
            # 同步正文一级标题
            d["text"] = d["text"].replace("# " + old + "\n", "# " + cand_title + "\n", 1)
        else:
            seen[key] = 0

    rows = build_queries(rs, docs, qseed)

    lens = [len(d["text"]) for d in docs]
    print("docs=%d  queries=%d  conversations=%d" % (len(docs), len(rows), len(rows) // 2))
    print("文档长度 min=%d max=%d avg=%.1f 总字符=%d" % (min(lens), max(lens), sum(lens) / len(lens), sum(lens)))
    from collections import Counter
    print("领域分布:", dict(Counter(d["domain"] for d in docs)))
    print("intentHint:", dict(Counter(r["intentHint"] for r in rows)))

    if not args.check:
        write_jsonl(CORPUS_DIR / "docs.jsonl", docs)
        write_jsonl(CORPUS_DIR / "queries.jsonl", rows)
        print("已写入:", CORPUS_DIR / "docs.jsonl")
        print("已写入:", CORPUS_DIR / "queries.jsonl")
    return 0


if __name__ == "__main__":
    sys.exit(main())
