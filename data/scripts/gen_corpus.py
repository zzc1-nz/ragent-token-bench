# 问题措辞变体：同一事实在不同会话中以不同问法出现，避免评测集出现大量重复问题
Q_PREFIX = ["", "想确认一下，", "麻烦问下，", "想了解一下，", "请教一下，", "有个问题，"]
Q_SUFFIX = ["", "？", "？麻烦说下具体规定。", "？最好能说清时限。", "？这个有明确标准吗？", "？"]

FU_PREFIX = ["", "再确认一下，", "另外想问，", "顺着上面问，", "还有个细节，", "补充问一下，"]


def vary_question(q, n, is_followup=False):
    """按出现次数轮转变体，保证 500 轮里同一模板的问题措辞不重复。

    追问轮强制带指代词（「那/它/这个/该」等），确保必须依赖上一轮语境才能理解。
    """
    if is_followup:
        # 追问：先保证有指代锚点，再按次数加前缀做措辞变化
        base = q.rstrip("？")
        anchor = None
        for w in ("那", "它", "这个", "那个", "该", "这", "其"):
            if w in base:
                anchor = w
                break
        if anchor is None:
            base = "那" + base
        p = FU_PREFIX[n % len(FU_PREFIX)]
        if n < len(FU_PREFIX):
            return tidy_q(p + base + "？")
        return tidy_q(p + base.rstrip("呢") + "呢？")
    p = Q_PREFIX[n % len(Q_PREFIX)]
    s = Q_SUFFIX[(n // len(Q_PREFIX)) % len(Q_SUFFIX)]
    base = q.rstrip("？")
    if s in ("", "？"):
        return tidy_q(p + base + "？")
    return tidy_q(p + base + s)


def tidy_q(q):
    """清理问题里的多余空格与重复单位（保留「R5 贵」这类中英文间必要空格）。"""
    # 标点前的空格
    q = re.sub(r'\s+([？。，；：])', r'\1', q)
    # 重复单位
    q = q.replace("元 元", "元").replace("天 天", "天").replace("个 个", "个")
    q = q.replace(" 元。", " 元。").replace("元元", "元")
    # 中文之间的多余空格（英文/数字两侧保留）
    q = re.sub(r'(?<=[\u4e00-\u9fa5]) +(?=[\u4e00-\u9fa5])', '', q)
    # 连续空格压缩
    q = re.sub(r' {2,}', ' ', q)
    return q.strip()


def build_queries(rs, docs, qseed):
    by_domain = {}
    for d in docs:
        by_domain.setdefault(d["domain"], []).append(d)
    theme_doc = {}   # (domain, 首个章节生成器) -> [docId]
    for d in docs:
        info = qseed[d["docId"]]
        theme_doc.setdefault((d["domain"], info["theme"]), []).append(d["docId"])

    doc_ids = [d["docId"] for d in docs]
    # 会话 -> 主文档：前 200 个会话各用一篇，后 50 个复用前 50 篇
    conv_doc = [doc_ids[i] for i in range(200)] + [doc_ids[i] for i in range(50)]

    # intentHint 精确分布：213 kb / 25 chitchat / 12 system
    intents = ["kb"] * 213 + ["chitchat"] * 25 + ["system"] * 12
    rs.shuffle(intents)

    cursor = {d: 0 for d in doc_ids}
    qseen = {}   # 问题模板 -> 已出现次数，用于生成措辞变体
    n_chit = 0   # 闲聊模板独立轮转，保证不重复
    n_sys = 0    # 系统模板独立轮转
    rows = []
    ci = 0
    for c in range(250):
        conv = "CONV_%04d" % (c + 1)
        intent = intents[c]
        if intent == "chitchat":
            q, fu, ans = CHITCHAT[n_chit % len(CHITCHAT)]
            opening = CHIT_OPEN[n_chit % len(CHIT_OPEN)]
            n_chit += 1
            rows.append({"conversationId": conv, "turnIndex": 0, "question": q,
                         "referenceDocIds": [], "referenceAnswer": fit_answer(opening, "需要查资料随时说。"),
                         "intentHint": "chitchat"})
            rows.append({"conversationId": conv, "turnIndex": 1, "question": fu,
                         "referenceDocIds": [], "referenceAnswer": fit_answer(ans, "随时可以问我。"),
                         "intentHint": "chitchat"})
            continue
        if intent == "system":
            q, fu, ans = SYSTEM[n_sys % len(SYSTEM)]
            opening = SYS_OPEN[n_sys % len(SYS_OPEN)]
            n_sys += 1
            rows.append({"conversationId": conv, "turnIndex": 0, "question": q,
                         "referenceDocIds": [], "referenceAnswer": fit_answer(opening, "可查阅对应技术文档。"),
                         "intentHint": "system"})
            rows.append({"conversationId": conv, "turnIndex": 1, "question": fu,
                         "referenceDocIds": [], "referenceAnswer": fit_answer(ans, "可查阅对应技术文档。"),
                         "intentHint": "system"})
            continue

        did = conv_doc[ci]
        ci += 1
        info = qseed[did]
        seeds = info["seeds"]
        if not seeds:
            raise RuntimeError("文档 %s 没有 QA 种子" % did)
        pos = cursor[did] % len(seeds)
        cursor[did] += 1
        seed, gname = seeds[pos]

        refs = [did]
        extra = [x for x in theme_doc.get((info["domain"], gname), []) if x != did]
        if extra:
            refs.append(extra[0])
            if len(extra) > 1 and rs.random() < 0.35:
                refs.append(extra[1])
        refs = refs[:3]

        filler = "具体条款以文档正文为准。"
        nq = qseen.get(seed["q"], 0)
        qseen[seed["q"]] = nq + 1
        q0 = vary_question(seed["q"], nq, False)
        rows.append({"conversationId": conv, "turnIndex": 0, "question": q0,
                     "referenceDocIds": refs,
                     "referenceAnswer": fit_answer(seed["a"], filler),
                     "intentHint": "kb"})
        fu_q, fu_a = seed["fu"][0] if seed["fu"] else (seed["q"], seed["a"])
        nf = qseen.get(fu_q, 0)
        qseen[fu_q] = nf + 1
        fu_q = vary_question(fu_q, nf, True)
        rows.append({"conversationId": conv, "turnIndex": 1, "question": fu_q,
                     "referenceDocIds": refs,
                     "referenceAnswer": fit_answer(fu_a, filler),
                     "intentHint": "kb"})
    return rows


